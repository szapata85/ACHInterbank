using Cfa.ACHInterbank.Domain.Entities.Transactions.Enums;
using Cfa.ACHInterbank.Domain.Models.ACH;
using Cfa.ACHInterbank.Persistence.DataBase;
using Microsoft.EntityFrameworkCore;

namespace Cfa.ACHInterbank.Persistence.ACH.Services.Implementation;

/// <summary>
/// Evidence for R74 under CENIT Annex A and NACHA-M Annex 1.5: the original
/// monetary credit, not the R32 return, must carry payment information in a
/// type-05 addenda. Both ROR registration and physical emission use this gate.
/// </summary>
internal static class CenitR74OriginalCreditEvidence
{
    private static readonly HashSet<string> MonetaryCreditCodes = new(StringComparer.Ordinal)
    {
        "22", "32", "42", "52"
    };

    internal static async Task<bool> ExistsAsync(AchDbContext context, AchTransaction original, CancellationToken ct)
    {
        if (original.Type != TransactionTypeEnum.Credit || original.IsPrenotification || original.Amount <= 0
            || !MonetaryCreditCodes.Contains(original.TransactionCode?.Trim() ?? string.Empty))
            return false;

        var raw = await context.IncomingNachaTransactionLinks.AsNoTracking()
            .Include(x => x.AddendaRecord)
            .Include(x => x.EntryDetail)
            .Where(x => x.AchTransactionId == original.Id
                && x.AddendaRecord != null
                && x.AddendaRecord.CodeTypeAddendumRecord == "05"
                && (x.AddendaRecord.ReturnReasonCode == null || x.AddendaRecord.ReturnReasonCode == ""))
            .ToListAsync(ct);

        // Physical evidence takes precedence. An unrelated local reference
        // cannot repair an incomplete type-05 record already received.
        if (raw.Count > 0)
            return raw.Any(x => HasCorrelatedOriginalEntry(x, original) && HasValidPhysicalField3(x.AddendaRecord!));

        // Outgoing originals have not necessarily passed through the incoming
        // parser. Their own type-05 credit addenda provide the semantic source
        // for the 80-character payment field generated by NACHA-M.
        var own = await context.AchTransactionAddendas.AsNoTracking()
            .Where(x => x.AchTransactionId == original.Id && x.AddendaType == "05"
                && (x.ReturnReasonCode == null || x.ReturnReasonCode == ""))
            .ToListAsync(ct);
        return HasNumericOriginator(original.CompanyIdentification)
            && own.Any(x => HasInformation(x.Information) || HasInformation(x.Reference));
    }

    private static bool HasCorrelatedOriginalEntry(IncomingNachaTransactionLink link, AchTransaction original)
    {
        var entry = link.EntryDetail;
        var addenda = link.AddendaRecord;
        var code = entry?.TransactionCode?.Trim();
        return link.IsFinal
            && entry is not null && addenda is not null
            && entry.EntryDetailID == addenda.EntryDetailId
            && string.Equals(entry.NachaID, addenda.NachaID, StringComparison.Ordinal)
            && string.Equals(entry.SequenceNumber?.Trim(), original.TraceNumber?.Trim(), StringComparison.Ordinal)
            && entry.Amount == original.Amount
            && code is not null && MonetaryCreditCodes.Contains(code)
            && string.Equals(code, original.TransactionCode?.Trim(), StringComparison.Ordinal);
    }

    internal static bool HasValidPhysicalField3(AddendaRecord record)
    {
        if (record.CodeTypeAddendumRecord != "05" || !string.IsNullOrWhiteSpace(record.ReturnReasonCode))
            return false;

        // Official CENIT profiles store the whole field 3 in this property;
        // the parser trims trailing blanks, so restore them before checking
        // Annex 1.5 PPD credit reserved positions.
        var field = record.PaymentRelatedInformation;
        if (field is not null)
        {
            if (field.Length > 80) return false;
            var padded = field.PadRight(80, ' ');
            return HasNumericOriginator(padded[..15])
                && padded.Substring(15, 2) == "  "
                && padded.Substring(51, 2) == "  "
                && padded.Substring(77, 3) == "   ";
        }

        // Legacy split PPD records: require the mandatory originator ID, not
        // a free-text purpose, invoice number or return addenda metadata alone.
        return HasNumericOriginator(record.IdUserOrig);
    }

    private static bool HasNumericOriginator(string? value)
    {
        var trimmed = value?.Trim();
        return !string.IsNullOrEmpty(trimmed)
            && trimmed.All(char.IsAsciiDigit)
            && trimmed.Any(c => c != '0');
    }

    private static bool HasInformation(string? value)
        => !string.IsNullOrWhiteSpace(value) && value.Any(c => c != '0' && c != ' ');
}
